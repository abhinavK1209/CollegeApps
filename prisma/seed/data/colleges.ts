import type { ApplicationPlatform, CollegeType } from "@prisma/client";

/**
 * Curated college identity data.
 *
 * Deliberately contains NO statistics — no admit rates, no test score ranges, no
 * cost figures. Those are populated by `pnpm db:import:scorecard`, which pulls
 * them from the U.S. Department of Education's College Scorecard API.
 *
 * The split is intentional: identity (name, location, which application platform
 * a college uses) is stable and verifiable, while statistics change yearly and
 * must come from an authoritative source. A wrong admit rate is worse than a
 * missing one when you're deciding where to apply.
 *
 * Every row seeds with dataSource "curated" and dataVerifiedAt null, so the UI
 * can show a "verify on the college's site" affordance. See risk R1.
 */
